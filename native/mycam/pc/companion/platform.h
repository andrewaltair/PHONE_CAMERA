#pragma once
// What the companion needs from the operating system, behind one interface: platform_win.cpp (Windows) and
// platform_posix.cpp (Linux). Shared code calls these instead of Win32 or POSIX directly. Sockets are in net.h.

#include <stddef.h>
#include <stdint.h>

#include <string>
#include <vector>

namespace mycam {

// --- Time ------------------------------------------------------------------------------------------------
uint64_t NowMs();              // Monotonic milliseconds (GetTickCount64 on Windows).
void SleepMs(uint32_t ms);
uint64_t UnixTime();           // Seconds since 1970.

// --- Text ------------------------------------------------------------------------------------------------
std::wstring Wide(const std::string& utf8);
std::string Utf8(const std::wstring& wide);
std::string ComputerName();    // UTF-8; "PC" if unknown.

// --- Network adapters -----------------------------------------------------------------------------------
struct Adapter {
    uint32_t ipv4 = 0;         // Network order.
    uint8_t prefix = 0;        // On-link prefix length; 0 if unknown.
    uint32_t ifType = 0;       // IANA type (6 Ethernet, 24 loopback, 71 Wi-Fi, 131 tunnel, 53 virtual).
    std::wstring name;         // "Wi-Fi", "wlp2s0"...
    std::wstring description;  // What web::ClassifyAdapter reads ("Intel(R) Wi-Fi 6", "Apple Mobile Device...").
};
std::vector<Adapter> UpAdapters(); // Every IPv4 address on an adapter that is up.

// --- Settings store -------------------------------------------------------------------------------------
// Small named values under a path of '/'-separated keys ("PairedPhones/<id>"): the registry under
// HKCU\Software\MyCam on Windows (the keys earlier versions wrote), ~/.config/mycam/store/ on Linux (this
// user only). Strings are UTF-8.
bool StoreGetBytes(const std::string& path, const std::string& name, std::vector<uint8_t>* value);
bool StoreSetBytes(const std::string& path, const std::string& name, const std::vector<uint8_t>& value);
bool StoreGetString(const std::string& path, const std::string& name, std::string* value);
bool StoreSetString(const std::string& path, const std::string& name, const std::string& value);
bool StoreGetU64(const std::string& path, const std::string& name, uint64_t* value);
bool StoreSetU64(const std::string& path, const std::string& name, uint64_t value);
std::vector<std::string> StoreList(const std::string& path); // Its sub-paths' last parts.
void StoreDelete(const std::string& path);                   // With everything under it.

// Secrets at rest (pairing keys): DPAPI on Windows. On Linux, as-is: the store is readable by this user only.
bool Protect(const std::vector<uint8_t>& plain, std::vector<uint8_t>* out);
bool Unprotect(const std::vector<uint8_t>& stored, std::vector<uint8_t>* plain);

// --- Embedded files -------------------------------------------------------------------------------------
// The iPhone page's files and the status pictures, by their companion.rc id ("" if missing): exe resources
// on Windows, compiled in on Linux (web_assets.cpp, generated by pc/linux.cmake).
std::string ResourceData(int id);

} // namespace mycam
